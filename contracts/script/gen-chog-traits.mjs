// Packs the REAL Chog Genesis traits (1,969 tokens) into Solidity data contracts so the testnet Chog's tokenURI can
// carry the real traits on-chain, next to its live Daemon state.
//
// Usage: node script/gen-chog-traits.mjs [dir]
//   dir = folder with <1..1969>.json copies of the collection metadata (downloaded from IPFS if a file is missing).
// Writes src/chog/data/ChogTraitRows0.sol, ChogTraitRows1.sol and ChogTraitNames.sol.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = process.argv[2] ?? join(root, "script", ".chog-metadata");
const META = "bafybeid4ybujnscdipkno7ps5utqelp5ry5ryreqhay3zhgk3a6x4jruqu";
const GATEWAYS = ["https://ipfs.filebase.io/ipfs", "https://gateway.pinata.cloud/ipfs"];
const SUPPLY = 1969;
const SPLIT = 985; // tokens 1..985 in Rows0, 986..1969 in Rows1 (each stays under the 24 KB contract limit)

mkdirSync(dir, { recursive: true });

async function load(id) {
  const file = join(dir, `${id}.json`);
  if (existsSync(file)) {
    try {
      return JSON.parse(readFileSync(file, "utf8"));
    } catch {
      /* re-download */
    }
  }
  for (const g of GATEWAYS) {
    try {
      const res = await fetch(`${g}/${META}/${id}.json`, { signal: AbortSignal.timeout(30_000) });
      if (!res.ok) continue;
      const text = await res.text();
      const json = JSON.parse(text);
      writeFileSync(file, text);
      return json;
    } catch {
      /* next gateway */
    }
  }
  throw new Error(`could not load metadata for ${id}`);
}

const tokens = [];
for (let id = 1; id <= SUPPLY; id++) tokens.push(await load(id));

// trait types in order of first appearance; values sorted so the output is stable
const types = [];
const values = new Map();
for (const t of tokens) {
  for (const a of t.attributes) {
    if (!values.has(a.trait_type)) {
      values.set(a.trait_type, new Set());
      types.push(a.trait_type);
    }
    values.get(a.trait_type).add(String(a.value));
  }
}
const lists = types.map((t) => [...values.get(t)].sort());
for (const s of [...types, ...lists.flat()]) {
  if (/["\\\u0000-\u001f]/.test(s) || Buffer.byteLength(s) > 255) throw new Error(`unsafe trait text: ${s}`);
}
if (types.length > 16 || lists.some((l) => l.length > 255)) throw new Error("trait table too large for one byte per trait");

// one row per token: one byte per trait type = value index + 1 (0 = this token has no such trait)
const rowFor = (t) =>
  types.map((type, i) => {
    const a = t.attributes.find((x) => x.trait_type === type);
    return a ? lists[i].indexOf(String(a.value)) + 1 : 0;
  });
const rows = tokens.map(rowFor);
const hex = (bytes) => Buffer.from(bytes).toString("hex");
const bytesOf = (from, to) => rows.slice(from, to).flat();

// names blob: per type [len][type name][count][len][value]...; offsets point at each type block
const blob = [];
const offsets = [];
for (let i = 0; i < types.length; i++) {
  offsets.push(blob.length);
  const tn = Buffer.from(types[i]);
  blob.push(tn.length, ...tn, lists[i].length);
  for (const v of lists[i]) {
    const b = Buffer.from(v);
    blob.push(b.length, ...b);
  }
}
if (blob.length > 60_000) throw new Error("names blob too large");

const out = join(root, "src", "chog", "data");
mkdirSync(out, { recursive: true });
const header = "// SPDX-License-Identifier: MIT\npragma solidity ^0.8.24;\n\n// AUTO-GENERATED by script/gen-chog-traits.mjs from the real Chog Genesis metadata. Do not edit.\n\n";
const wrap = (long) => long.match(/.{1,100}/g).map((l) => `        hex"${l}"`).join("\n");

for (const [name, from, to, firstId] of [
  ["ChogTraitRows0", 0, SPLIT, 1],
  ["ChogTraitRows1", SPLIT, SUPPLY, SPLIT + 1],
]) {
  writeFileSync(
    join(out, `${name}.sol`),
    `${header}/// @notice Packed trait rows for artwork ids ${firstId}..${to}: ${types.length} bytes per token (value index + 1, 0 = none).\ncontract ${name} {\n    uint256 public constant FIRST_ID = ${firstId};\n    uint256 public constant LAST_ID = ${to};\n    uint256 public constant ROW_BYTES = ${types.length};\n\n    function rows() external pure returns (bytes memory) {\n        return\n${wrap(hex(bytesOf(from, to)))};\n    }\n}\n`,
  );
}
writeFileSync(
  join(out, "ChogTraitNames.sol"),
  `${header}/// @notice Trait type and value names of the real Chog Genesis collection (${types.length} types).\ncontract ChogTraitNames {\n    uint256 public constant TYPE_COUNT = ${types.length};\n\n    function names() external pure returns (bytes memory) {\n        return\n${wrap(hex(blob))};\n    }\n\n    function offsets() external pure returns (uint16[${types.length}] memory o) {\n        o = [${offsets.map((x) => `uint16(${x})`).join(", ")}];\n    }\n}\n`,
);

// the reference the on-chain output is checked against (artwork id -> [[type, value], ...] in type order)
const expected = tokens.map((t) => types.map((type) => [type, (t.attributes.find((a) => a.trait_type === type) ?? {}).value ?? null]).filter(([, v]) => v !== null));
writeFileSync(join(dir, "expected.json"), JSON.stringify(expected));
console.log(`types: ${types.join(", ")}`);
console.log(`row bytes ${rows.flat().length}, names blob ${blob.length} bytes; wrote ${out}`);
