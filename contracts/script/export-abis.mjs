// Generates typed `as const` ABIs from Foundry artifacts for the frontend and keeper.
// Usage (after `forge build`): node script/export-abis.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// export name -> [source file, contract name]
const ABIS = {
  daemonAccountAbi: ["DaemonAccount.sol", "DaemonAccount"],
  daemonHubAbi: ["DaemonHub.sol", "DaemonHub"],
  yieldSourceAbi: ["RewardVault.sol", "RewardVault"],
  degenVaultAbi: ["DegenVault.sol", "DegenVault"],
  strategyRegistryAbi: ["StrategyRegistry.sol", "StrategyRegistry"],
  erc6551RegistryAbi: ["IERC6551.sol", "IERC6551Registry"],
  mockChogAbi: ["MockChog.sol", "MockChog"],
  erc20Abi: ["MockERC20.sol", "MockERC20"],
  priceOracleAbi: ["MockOracle.sol", "MockOracle"],
  routerAbi: ["MockRouter.sol", "MockRouter"],
};

const header = `// AUTO-GENERATED by contracts/script/export-abis.mjs from Foundry artifacts. Do not edit.\n`;
let body = header;
for (const [name, [file, contract]] of Object.entries(ABIS)) {
  const artifact = JSON.parse(readFileSync(join(root, "out", file, `${contract}.json`), "utf8"));
  body += `\nexport const ${name} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
}

for (const target of ["../frontend/lib/abis.generated.ts", "../keeper/src/abis.generated.ts"]) {
  writeFileSync(join(root, target), body);
  console.log("wrote", target);
}
